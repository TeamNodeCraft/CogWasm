//! Deterministic benchmark-program generators.
//!
//! `large` is a Rust port of `bench/scripts/gen_large.py` (144 inline modules,
//! about 100k lines). The Python generator uses `random.Random`, so the port
//! below includes `CPython`'s `MT19937` seeding and `getrandbits`/`randrange`
//! semantics; the output is byte-for-byte what the script writes for the same
//! seed. `stress` is the deterministic 1,024-function generator from
//! `bench/scripts/gen_stress.py`.

/// The large program's default seed, matching `gen_large.py`.
pub const LARGE_SEED: u64 = 20_261_123;
/// The large program's default module count.
pub const LARGE_MODULES: usize = 144;
/// The large program's default stages per module.
pub const LARGE_STAGES: usize = 12;

/// Generate the `large` benchmark program.
#[must_use]
pub fn generate_large(prelude: &str, modules: usize, stages: usize, seed: u64) -> String {
    let mut rng = PythonRandom::new(seed);
    let mut text = render(
        r#"
// Generated by bench/scripts/gen_large.py (seed {seed}). Do not edit.
// {modules} modules, 0 functions, about 0 lines.
#![no_std]
#![allow(dead_code, unused_variables, unused_mut, unused_imports, clippy::all)]

include!("{prelude}");

"#,
        &[
            ("seed", seed.to_string()),
            ("modules", modules.to_string()),
            ("prelude", prelude.to_owned()),
        ],
    );
    text.push_str(SUPPORT);
    for module in 0..modules {
        text.push_str(&module_text(&mut rng, module, stages));
    }
    let names = (0..modules)
        .map(|module| format!("m{module:03}::run"))
        .collect::<Vec<_>>()
        .join(",\n    ");
    text.push_str(&render(
        r#"
static MODULES: [fn(u64) -> u64; {modules}] = [
    {names},
];

fn body(seed: u64) -> u64 {
    let mut acc = splitmix64(seed);
    let mut index = 0usize;
    while index < MODULES.len() {
        acc = acc.rotate_left(1) ^ MODULES[index](acc);
        if index % 16 == 0 {
            emit_u64(acc);
        }
        index += 1;
    }
    emit_u64(acc);
    acc
}

const BENCH_EDIT_TWEAK: u64 = 0u64;
#[unsafe(no_mangle)]
pub extern "C" fn bench_edit_probe() -> u64 {
    BENCH_EDIT_TWEAK
}
"#,
        &[("modules", modules.to_string()), ("names", names)],
    ));
    let line_count = text.lines().count();
    text.replace(
        &format!("// {modules} modules, 0 functions, about 0 lines."),
        &format!("// {modules} modules, about {line_count} lines."),
    )
}

/// Generate the `generated_stress` program (1,024 functions across 16 modules).
#[must_use]
#[expect(
    clippy::too_many_lines,
    reason = "the generator mirrors the Python script's flat loops"
)]
pub fn generate_stress(prelude: &str) -> String {
    const TRAITS: usize = 8;
    const TYPES: usize = 8;
    const VARIANTS: usize = 128;
    const FUNCTIONS_PER_MODULE: usize = 128;
    let mut text = render(
        r#"
// Generated by bench/scripts/gen_stress.py. Do not edit.
#![no_std]

include!("{prelude}");

"#,
        &[("prelude", prelude.to_owned())],
    );
    for trait_index in 0..TRAITS {
        text.push_str(&render(
            "trait T{trait_index} { fn v{trait_index}(&self) -> u64; }\n",
            &[("trait_index", trait_index.to_string())],
        ));
    }
    for type_index in 0..TYPES {
        text.push_str(&render(
            "struct S{type_index} { field: u64 }\n\
             impl S{type_index} { const fn new(field: u64) -> Self { Self { field } } }\n",
            &[("type_index", type_index.to_string())],
        ));
        for trait_index in 0..TRAITS {
            text.push_str(&render(
                "impl T{trait_index} for S{type_index} { #[inline] fn v{trait_index}(&self) -> u64 { {value} } }\n",
                &[
                    ("trait_index", trait_index.to_string()),
                    ("type_index", type_index.to_string()),
                    ("value", stress_value_expr(type_index)),
                ],
            ));
        }
    }
    let bounds = (0..TRAITS)
        .map(|trait_index| format!("T{trait_index}"))
        .collect::<Vec<_>>()
        .join(" + ");
    text.push_str(&render(
        r"
#[inline(never)]
fn combine<T: {bounds}>(value: &T, seed: u64) -> u64 {
    let mut acc = seed;
",
        &[("bounds", bounds)],
    ));
    for trait_index in 0..TRAITS {
        text.push_str("    acc = acc.wrapping_mul(0x9e37_79b9_7f4a_7c15).wrapping_add(value.v");
        text.push_str(&trait_index.to_string());
        text.push_str("());\n");
    }
    text.push_str("    acc\n}\n\n");
    let groups = (TYPES * VARIANTS) / FUNCTIONS_PER_MODULE;
    for group in 0..groups {
        text.push_str("mod part");
        text.push_str(&group.to_string());
        text.push_str(" {\n");
        for offset in 0..FUNCTIONS_PER_MODULE {
            let index = group * FUNCTIONS_PER_MODULE + offset;
            let type_index = index / VARIANTS;
            let variant = index % VARIANTS;
            text.push_str(&indent_lines(
                &render(
                    r"
    #[inline(never)]
    pub fn w_{type_index}_{variant}(seed: u64) -> u64 {
        let value = super::S{type_index}::new(seed ^ {seed_xor});
        super::combine(&value, seed)
    }

",
                    &[
                        ("type_index", type_index.to_string()),
                        ("variant", variant.to_string()),
                        ("seed_xor", (variant * 2_654_435_761 + 1).to_string()),
                    ],
                ),
                4,
            ));
        }
        text.push_str("}\n\n");
    }
    let count = TYPES * VARIANTS;
    let names = (0..TYPES)
        .flat_map(|type_index| {
            (0..VARIANTS).map(move |variant| {
                format!(
                    "part{}::w_{type_index}_{variant}",
                    (type_index * VARIANTS + variant) / FUNCTIONS_PER_MODULE
                )
            })
        })
        .collect::<Vec<_>>()
        .join(", ");
    text.push_str(&render(
        r"
static FUNCTIONS: [fn(u64) -> u64; {count}] = [{names}];

fn body(seed: u64) -> u64 {
    let mut acc = 0u64;
    let mut index = 0usize;
    while index < FUNCTIONS.len() {
        acc = acc.wrapping_add(FUNCTIONS[index](seed));
        if index % 64 == 0 {
            emit_u64(acc);
        }
        index += 1;
    }
    emit_u64(acc);
    acc
}
",
        &[("count", count.to_string()), ("names", names)],
    ));
    text
}

fn stress_value_expr(type_index: usize) -> String {
    format!(
        "self.field.wrapping_mul({}).wrapping_add({})",
        type_index + 3,
        type_index * 17 + 1
    )
}

fn stage_body(rng: &mut PythonRandom, module: usize, stage: usize) -> String {
    let _ = module;
    let constant = rng.randrange(1 << 32, 1 << 63);
    let mask = rng.randrange(3, 15);
    let shift = rng.randrange(1, 31);
    let call = if let Some(previous) = stage.checked_sub(1) {
        format!("    acc = acc.wrapping_add(stage_{previous:02}(acc, depth.saturating_sub(1)));\n")
    } else {
        "    acc = acc.wrapping_add(small(acc));\n".to_owned()
    };
    let arms = (0..8)
        .map(|index| {
            let prefix = if index < 7 {
                format!("        {index} => ")
            } else {
                "        _ => ".to_owned()
            };
            let expression = format!(
                "acc.wrapping_add(0x{:x})",
                constant ^ (u64::try_from(index).unwrap_or(0) * 0x9e37_79b9)
            );
            let suffix = if index % 2 == 0 {
                ".wrapping_mul(index as u64 + 1)".to_owned()
            } else {
                ".rotate_left(index as u32)".to_owned()
            };
            format!("{prefix}{expression}{suffix},")
        })
        .collect::<Vec<_>>()
        .join("\n");
    render(
        r"
    #[inline(never)]
    fn stage_{stage}(seed: u64, depth: u32) -> u64 {
        let mut acc = seed ^ 0x{constant};
        let mut buffer: alloc::vec::Vec<u64> = alloc::vec::Vec::with_capacity(24);
        let mut index = 0usize;
        while index < 24 {
            let raw = (index as u64)
                .wrapping_mul(0x{constant})
                .wrapping_add(seed.rotate_left((index % {shift}) as u32));
            if raw & {mask} == 0 {
                index += 1;
                continue;
            }
            buffer.push(match raw & 7 {
                0 => raw.wrapping_add(0x{low}),
                1 => raw.wrapping_mul(3).rotate_left(7),
                2 => raw ^ 0x{constant},
                3 => raw.wrapping_sub(index as u64),
                4 => raw.rotate_right((index % 29) as u32),
                5 => raw.wrapping_add(0x9e37_79b9_7f4a_7c15),
                6 => raw.wrapping_mul(0xbf58_476d_1ce4_e5b9),
                _ => raw.wrapping_add(0x94d0_49bb_1331_11eb),
            });
            index += 1;
        }
        let folded = buffer
            .iter()
            .copied()
            .enumerate()
            .filter(|(slot, value)| (value ^ *slot as u64) & 1 == 0)
            .map(|(slot, value)| value.rotate_left((slot % {shift}) as u32))
            .fold(acc, |left, right| left.wrapping_add(right));
        acc = acc.wrapping_mul(0x{constant}).wrapping_add(folded);
{call}        match acc & 7 {
{arms}
        }
    }

",
        &[
            ("stage", format!("{stage:02}")),
            ("constant", format!("{constant:x}")),
            ("shift", shift.to_string()),
            ("mask", mask.to_string()),
            ("low", format!("{:x}", constant & 0xffff)),
            ("call", call),
            ("arms", arms),
        ],
    )
}

#[expect(
    clippy::too_many_lines,
    reason = "the generator mirrors the Python script line for line"
)]
fn module_text(rng: &mut PythonRandom, module: usize, stages: usize) -> String {
    let name = format!("m{module:03}");
    let key = format!("Key{module}");
    let value = format!("Value{module}");
    let record = format!("Record{module}");
    let kind = format!("Kind{module}");
    let mut text = render(
        r"
// >>> {name}
mod {name} {
    use super::support::{Metric, Reducer, Table, Window, checksum, combine, mix};
    use super::emit_u64;

    #[derive(Clone, Copy, PartialEq)]
    pub struct {key}(pub u32);

    #[derive(Clone, Copy)]
    pub struct {value}(pub u32);

    impl From<{value}> for u64 {
        #[inline]
        fn from(value: {value}) -> u64 {
            value.0 as u64
        }
    }

    #[derive(Clone, Copy)]
    pub struct {record} {
        pub id: u32,
        pub weight: u64,
        pub flags: u16,
    }

    #[derive(Clone, Copy)]
    pub enum {kind} {
        Alpha(u64),
        Beta { value: u32 },
        Gamma(u16),
    }

",
        &[
            ("name", name.clone()),
            ("key", key.clone()),
            ("value", value.clone()),
            ("record", record.clone()),
            ("kind", kind.clone()),
        ],
    );
    let const_a = rng.randrange(1 << 16, 1 << 40);
    let const_b = rng.randrange(1 << 16, 1 << 40);
    text.push_str(&indent_lines(
        &render(
            r"
    impl Metric for {record} {
        #[inline]
        fn score(&self) -> u64 {
            self.weight
                .wrapping_mul(0x{const_a})
                .wrapping_add((self.id as u64).rotate_left((self.flags % 31) as u32))
        }

        #[inline]
        fn weight(&self) -> u32 {
            (self.flags as u32).wrapping_add(self.id)
        }
    }

    impl Metric for {kind} {
        #[inline]
        fn score(&self) -> u64 {
            match *self {
                {kind}::Alpha(value) => value.wrapping_mul(0x{const_a}),
                {kind}::Beta { value } => (value as u64).rotate_left(11),
                {kind}::Gamma(value) => (value as u64).wrapping_add(0x{const_b}),
            }
        }

        #[inline]
        fn weight(&self) -> u32 {
            match *self {
                {kind}::Alpha(value) => value as u32,
                {kind}::Beta { value } => value,
                {kind}::Gamma(value) => value as u32,
            }
        }
    }

    impl Reducer for {record} {
        #[inline(never)]
        fn reduce(&self, seed: u64) -> u64 {
            let parts = [self.id as u64, self.weight, self.flags as u64];
            checksum::<3>(seed, &parts)
        }
    }

",
            &[
                ("record", record.clone()),
                ("kind", kind.clone()),
                ("const_a", format!("{const_a:x}")),
                ("const_b", format!("{const_b:x}")),
            ],
        ),
        4,
    ));
    text.push_str(&indent_lines(
        &render(
            r"
    #[inline]
    fn small(value: u64) -> u64 {
        mix(value, 0x{const_b}).wrapping_add(0x{low})
    }

",
            &[
                ("const_b", format!("{const_b:x}")),
                ("low", format!("{:x}", const_a & 0xffff)),
            ],
        ),
        4,
    ));
    for stage in 0..stages {
        if module == 16 && stage == 6 {
            text.push_str("    // @edit:signature\n");
        }
        text.push_str(&stage_body(rng, module, stage));
    }
    if module == 64 {
        text.push_str(&indent_lines(
            &render(
                r"
    // @edit:one-function
    #[inline(never)]
    pub fn hot_edit(seed: u64) -> u64 {
        let mut acc = seed.wrapping_mul(0x9e37_79b9_7f4a_7c15);
        acc = acc.rotate_left(13).wrapping_add(0x1234_5678);
        acc ^ seed.rotate_right(7)
    }

",
                &[],
            ),
            4,
        ));
    }
    if module == 48 {
        text.push_str(&indent_lines(
            &render(
                r"
    // @edit:struct-layout
    pub struct Packet{module} {
        pub tag: u16,
        pub payload: u64,
    }

",
                &[("module", module.to_string())],
            ),
            4,
        ));
    }
    if module == 32 {
        text.push_str(&indent_lines(
            &render(
                r"
    // @edit:add-function
    #[inline(never)]
    pub fn added_{module03}(seed: u64) -> u64 {
        let words = [seed, seed.rotate_left(9), seed ^ 0x55aa];
        checksum::<3>(seed, &words)
    }

",
                &[
                    ("module03", format!("{module:03}")),
                    ("module", module.to_string()),
                ],
            ),
            4,
        ));
    }
    let calls = (0..stages)
        .map(|stage| format!("        acc = acc.wrapping_add(stage_{stage:02}(acc, 1));"))
        .collect::<Vec<_>>()
        .join("\n");
    text.push_str(&indent_lines(&render(
        r"
    #[inline(never)]
    pub fn run(seed: u64) -> u64 {
        let mut table: Table<{key}, u64> = Table::new();
        let mut window: Window<{value}> = Window::new();
        let mut index = 0u32;
        while index < 24 {
            table.insert({key}(index.wrapping_mul(9).wrapping_add({module})), (index as u64).wrapping_add(seed));
            window.push({value}(index.wrapping_mul(3).wrapping_add({module})));
            index += 1;
        }
        let samples = [
            seed ^ 0x{const_a},
            seed.rotate_left(13),
            mix(seed, 0x{const_b}),
        ];
        let mut acc = combine(seed, &samples);
",
        &[
            ("key", key.clone()),
            ("value", value.clone()),
            ("module", module.to_string()),
            ("const_a", format!("{const_a:x}")),
            ("const_b", format!("{const_b:x}")),
        ],
    ), 4));
    if module == 32 {
        text.push_str("        acc = acc.wrapping_add(added_032(seed));\n");
    }
    text.push_str(&calls);
    text.push('\n');
    if module == 64 {
        text.push_str("        acc = acc.wrapping_add(hot_edit(seed));\n");
    }
    if module == 48 {
        text.push_str(
            "        let packet = Packet48 { tag: (seed as u16) ^ 48, payload: acc }; \
             acc = acc.wrapping_add(packet.payload ^ packet.tag as u64);\n",
        );
    }
    text.push_str(&render(
        r"        let record = {record} {
            id: (seed as u32).wrapping_add({module}),
            weight: acc.rotate_left(5),
            flags: (seed as u16) ^ {module},
        };
        let kind = {kind}::Beta { value: acc as u32 };
        let metrics: [&dyn Metric; 2] = [&record, &kind];
        for metric in metrics {
            acc = acc.wrapping_add(metric.score());
            acc = acc.rotate_left(metric.weight() % 31);
        }
        acc = acc.wrapping_add(table.lookup({key}({module} * 9)).unwrap_or(0));
        acc = acc.wrapping_add(table.len() as u64);
        acc = acc.wrapping_add(window.weighted_sum(acc));
        acc = acc.wrapping_add(record.reduce(acc));
        emit_u64(acc);
        acc
    }
}
// <<< {name}

",
        &[
            ("record", record.clone()),
            ("kind", kind.clone()),
            ("key", key),
            ("module", module.to_string()),
            ("name", name),
        ],
    ));
    text
}

/// Add `spaces` leading spaces to every non-empty line.
fn indent_lines(text: &str, spaces: usize) -> String {
    let prefix = " ".repeat(spaces);
    let mut output = String::with_capacity(text.len() + spaces * text.lines().count());
    for line in text.lines() {
        if !line.is_empty() {
            output.push_str(&prefix);
        }
        output.push_str(line);
        output.push('\n');
    }
    output
}

/// Replace `{name}` placeholders in a dedented template. Braces that are not
/// placeholders (Rust struct literals) stay literal; this is deliberately not
/// `format!`, because the generated code is full of braces.
fn render(template: &str, values: &[(&str, String)]) -> String {
    let mut output = dedent(template);
    for (key, value) in values {
        output = output.replace(&format!("{{{key}}}"), value);
    }
    output
}

/// Strip the common leading indentation and the leading newline from a raw
/// template, leaving the generated program's own indentation intact.
fn dedent(template: &str) -> String {
    let template = template.strip_prefix('\n').unwrap_or(template);
    let minimum = template
        .lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| line.len() - line.trim_start().len())
        .min()
        .unwrap_or(0);
    let mut output = String::with_capacity(template.len());
    for line in template.lines() {
        output.push_str(line.get(minimum..).unwrap_or(""));
        output.push('\n');
    }
    output
}

const SUPPORT: &str = r"
// >>> support
mod support {
    use super::splitmix64;
    use alloc::vec::Vec;

    pub trait Metric {
        fn score(&self) -> u64;
        fn weight(&self) -> u32;
    }

    pub trait Reducer {
        fn reduce(&self, seed: u64) -> u64;
        #[inline]
        fn describe(&self) -> u64 {
            self.reduce(1)
        }
    }

    /// A tiny open-addressing-style table, generic over a module-local key.
    pub struct Table<K, V> {
        entries: Vec<(K, V)>,
    }

    impl<K: Copy + PartialEq, V: Copy> Table<K, V> {
        #[inline]
        pub fn new() -> Self {
            Table { entries: Vec::new() }
        }

        #[inline(never)]
        pub fn insert(&mut self, key: K, value: V) {
            let mut index = 0usize;
            while index < self.entries.len() {
                if self.entries[index].0 == key {
                    // @edit:generic-insert
                    self.entries[index].1 = value;
                    return;
                }
                index += 1;
            }
            self.entries.push((key, value));
        }

        #[inline]
        pub fn lookup(&self, key: K) -> Option<V> {
            let mut index = 0usize;
            while index < self.entries.len() {
                if self.entries[index].0 == key {
                    return Some(self.entries[index].1);
                }
                index += 1;
            }
            None
        }

        #[inline]
        pub fn len(&self) -> usize {
            self.entries.len()
        }
    }

    /// A growable window of module-local values, summed through an iterator
    /// chain so every instantiation has a real MIR body.
    pub struct Window<T> {
        data: Vec<T>,
    }

    impl<T: Copy + Into<u64>> Window<T> {
        #[inline]
        pub fn new() -> Self {
            Window { data: Vec::new() }
        }

        #[inline]
        pub fn push(&mut self, value: T) {
            self.data.push(value);
        }

        #[inline(never)]
        pub fn weighted_sum(&self, seed: u64) -> u64 {
            self.data
                .iter()
                .enumerate()
                .filter(|(index, _)| index % 3 != 0)
                .map(|(index, value)| {
                    let value: u64 = (*value).into();
                    value
                        .wrapping_mul((index as u64).wrapping_add(1))
                        .rotate_left((index % 31) as u32)
                })
                .fold(seed, |acc, value| acc.wrapping_add(value))
        }
    }

    #[inline]
    pub fn mix(left: u64, right: u64) -> u64 {
        let x = left ^ right.rotate_left(17);
        x.wrapping_mul(0x9e37_79b9_7f4a_7c15).rotate_left(9)
    }

    #[inline(never)]
    pub fn combine(seed: u64, values: &[u64]) -> u64 {
        let mut acc = seed;
        let mut index = 0usize;
        while index < values.len() {
            acc = mix(acc, values[index]);
            acc = acc.wrapping_add(splitmix64(values[index] ^ (index as u64)));
            index += 1;
        }
        acc
    }

    /// A generic helper with a const parameter; every module uses it.
    #[inline(never)]
    pub fn checksum<const N: usize>(seed: u64, values: &[u64; N]) -> u64 {
        let mut acc = seed ^ (N as u64);
        let mut index = 0usize;
        while index < N {
            acc = acc.wrapping_add(values[index].rotate_left((index % 47) as u32));
            acc = mix(acc, values[index].wrapping_mul(index as u64 + 3));
            index += 1;
        }
        acc
    }
}
// <<< support

";

/// `CPython`'s `MT19937` `random.Random` for the operations `gen_large.py` uses.
///
/// The generator is seeded from the absolute integer seed's little-endian
/// 32-bit words, exactly like `random_seed` in `CPython`'s `_randommodule.c`.
/// `getrandbits` and `randrange` follow the same word selection and rejection
/// sampling; that is what makes the port byte-identical rather than merely
/// seeded.
struct PythonRandom {
    state: [u32; 624],
    index: usize,
}

impl PythonRandom {
    #[expect(
        clippy::cast_possible_truncation,
        reason = "the low 32 bits are the first CPython key word"
    )]
    fn new(seed: u64) -> Self {
        let mut random = Self {
            state: [0; 624],
            index: 624,
        };
        let mut key = Vec::with_capacity(2);
        key.push(seed as u32);
        if seed >> 32 != 0 {
            key.push((seed >> 32) as u32);
        }
        random.init_by_array(&key);
        random
    }

    #[expect(
        clippy::cast_possible_truncation,
        reason = "MT19937 indices are below 624"
    )]
    fn init_by_array(&mut self, key: &[u32]) {
        self.state[0] = 19_650_218;
        for index in 1..624 {
            let previous = self.state[index - 1];
            self.state[index] = 1_812_433_253u32
                .wrapping_mul(previous ^ (previous >> 30))
                .wrapping_add(index as u32);
        }
        let mut i = 1usize;
        let mut j = 0usize;
        let mut k = 624.max(key.len());
        while k > 0 {
            let previous = self.state[i - 1];
            self.state[i] = (self.state[i] ^ (previous ^ (previous >> 30)).wrapping_mul(1_664_525))
                .wrapping_add(key[j])
                .wrapping_add(j as u32);
            i += 1;
            j += 1;
            if i >= 624 {
                self.state[0] = self.state[623];
                i = 1;
            }
            if j >= key.len() {
                j = 0;
            }
            k -= 1;
        }
        for _ in 0..623 {
            let previous = self.state[i - 1];
            self.state[i] = (self.state[i]
                ^ (previous ^ (previous >> 30)).wrapping_mul(1_566_083_941))
            .wrapping_sub(i as u32);
            i += 1;
            if i >= 624 {
                self.state[0] = self.state[623];
                i = 1;
            }
        }
        self.state[0] = 0x8000_0000;
        self.index = 624;
    }

    fn genrand_uint32(&mut self) -> u32 {
        if self.index >= 624 {
            self.twist();
        }
        let mut value = self.state[self.index];
        self.index += 1;
        value ^= value >> 11;
        value ^= (value << 7) & 0x9d2c_5680;
        value ^= (value << 15) & 0xefc6_0000;
        value ^= value >> 18;
        value
    }

    fn twist(&mut self) {
        for index in 0..624 {
            let next = (index + 1) % 624;
            let following = (index + 397) % 624;
            let value = (self.state[index] & 0x8000_0000) | (self.state[next] & 0x7fff_ffff);
            self.state[index] = self.state[following] ^ (value >> 1);
            if value & 1 != 0 {
                self.state[index] ^= 0x9908_b0df;
            }
        }
        self.index = 0;
    }

    fn getrandbits(&mut self, bits: u32) -> u64 {
        if bits == 0 {
            return 0;
        }
        let words = bits.div_ceil(32);
        let mut result = 0u64;
        let mut remaining = bits;
        for word in 0..words {
            let mut value = self.genrand_uint32();
            if remaining < 32 {
                value >>= 32 - remaining;
            }
            result |= u64::from(value) << (32 * word);
            remaining = remaining.saturating_sub(32);
        }
        result
    }

    fn randrange(&mut self, start: u64, stop: u64) -> u64 {
        let width = stop.saturating_sub(start);
        debug_assert!(width > 0);
        let bits = 64 - width.leading_zeros();
        loop {
            let value = self.getrandbits(bits);
            if value < width {
                return start + value;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn python_random_matches_the_first_cpython_values() {
        // CPython 3.14: random.Random(20261123).randrange(1 << 32, 1 << 63)
        let mut rng = PythonRandom::new(LARGE_SEED);
        assert_eq!(rng.randrange(1 << 32, 1 << 63), 5_310_145_487_519_458_698);
    }

    #[test]
    fn large_generator_matches_the_python_fixture() {
        let expected = include_str!("../tests/fixtures/large-small.rs");
        let generated = generate_large("/private/tmp/prelude.rs", 2, 1, LARGE_SEED);
        assert_eq!(generated, expected);
    }

    #[test]
    fn large_generator_is_deterministic() {
        let first = generate_large("/tmp/prelude.rs", 2, 1, LARGE_SEED);
        let second = generate_large("/tmp/prelude.rs", 2, 1, LARGE_SEED);
        assert_eq!(first, second);
        assert!(first.contains("// 2 modules, about"));
        assert!(first.contains("mod m000"));
        assert!(first.contains("mod m001"));
    }

    #[test]
    fn stress_generator_is_deterministic_and_complete() {
        let text = generate_stress("/tmp/prelude.rs");
        assert_eq!(text, generate_stress("/tmp/prelude.rs"));
        assert!(text.contains("pub fn w_7_127"));
        assert!(text.contains("static FUNCTIONS: [fn(u64) -> u64; 1024]"));
        assert_eq!(text.matches("pub fn w_").count(), 1024);
    }
}
