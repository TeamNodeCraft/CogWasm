#!/usr/bin/env python3
"""Generate a ~100k-line Rust benchmark program for the V2 edit-loop work.

The output is deterministic for a given seed and is not checked in (it is far
too large); this generator is. The program is a realistic multi-module
``no_std + alloc`` crate: every module has structs, enums, trait impls, generic
instantiations (``Table<KeyN, u64>`` and ``Window<ValueN>`` are deliberately
instantiated with a module-local type so each module owns its monomorphised
copies), iterator chains, and a small call graph. The crate root dispatches to
every module from ``body`` and the prelude exports ``run(seed)``.

The source carries markers used by the phase-0 cacheability experiment
(``bench/scripts/v2_phase0.py``):

  @edit:one-function   a single function body in m064
  @edit:add-function   a new function in m032, called from m032::run
  @edit:signature      a signature change in m016 and its one caller
  @edit:struct-layout  an added field in m048's Record48
  @edit:generic-insert a body change in support::Table::insert, instantiated
                       once per module

Every edit is a real source change; none of them is required to preserve the
program's result (difftest compares the same source through both backends).

Usage:

    python3 bench/scripts/gen_large.py \
        --prelude bench/programs/prelude.rs \
        --out toolchain/work/v2/large/large.rs
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

HEADER = """// Generated by bench/scripts/gen_large.py (seed {seed}). Do not edit.
// {modules} modules, {functions} functions, about {lines} lines.
#![no_std]
#![allow(dead_code, unused_variables, unused_mut, unused_imports, clippy::all)]

include!("{prelude}");

"""

SUPPORT = r"""
// >>> support
mod support {
    use super::splitmix64;
    use alloc::vec::Vec;

    pub trait Metric {
        fn score(&self) -> u64;
        fn weight(&self) -> u32;
    }

    pub trait Reducer {
        fn reduce(&self, seed: u64) -> u64;
        #[inline]
        fn describe(&self) -> u64 {
            self.reduce(1)
        }
    }

    /// A tiny open-addressing-style table, generic over a module-local key.
    pub struct Table<K, V> {
        entries: Vec<(K, V)>,
    }

    impl<K: Copy + PartialEq, V: Copy> Table<K, V> {
        #[inline]
        pub fn new() -> Self {
            Table { entries: Vec::new() }
        }

        #[inline(never)]
        pub fn insert(&mut self, key: K, value: V) {
            let mut index = 0usize;
            while index < self.entries.len() {
                if self.entries[index].0 == key {
                    // @edit:generic-insert
                    self.entries[index].1 = value;
                    return;
                }
                index += 1;
            }
            self.entries.push((key, value));
        }

        #[inline]
        pub fn lookup(&self, key: K) -> Option<V> {
            let mut index = 0usize;
            while index < self.entries.len() {
                if self.entries[index].0 == key {
                    return Some(self.entries[index].1);
                }
                index += 1;
            }
            None
        }

        #[inline]
        pub fn len(&self) -> usize {
            self.entries.len()
        }
    }

    /// A growable window of module-local values, summed through an iterator
    /// chain so every instantiation has a real MIR body.
    pub struct Window<T> {
        data: Vec<T>,
    }

    impl<T: Copy + Into<u64>> Window<T> {
        #[inline]
        pub fn new() -> Self {
            Window { data: Vec::new() }
        }

        #[inline]
        pub fn push(&mut self, value: T) {
            self.data.push(value);
        }

        #[inline(never)]
        pub fn weighted_sum(&self, seed: u64) -> u64 {
            self.data
                .iter()
                .enumerate()
                .filter(|(index, _)| index % 3 != 0)
                .map(|(index, value)| {
                    let value: u64 = (*value).into();
                    value
                        .wrapping_mul((index as u64).wrapping_add(1))
                        .rotate_left((index % 31) as u32)
                })
                .fold(seed, |acc, value| acc.wrapping_add(value))
        }
    }

    #[inline]
    pub fn mix(left: u64, right: u64) -> u64 {
        let x = left ^ right.rotate_left(17);
        x.wrapping_mul(0x9e37_79b9_7f4a_7c15).rotate_left(9)
    }

    #[inline(never)]
    pub fn combine(seed: u64, values: &[u64]) -> u64 {
        let mut acc = seed;
        let mut index = 0usize;
        while index < values.len() {
            acc = mix(acc, values[index]);
            acc = acc.wrapping_add(splitmix64(values[index] ^ (index as u64)));
            index += 1;
        }
        acc
    }

    /// A generic helper with a const parameter; every module uses it.
    #[inline(never)]
    pub fn checksum<const N: usize>(seed: u64, values: &[u64; N]) -> u64 {
        let mut acc = seed ^ (N as u64);
        let mut index = 0usize;
        while index < N {
            acc = acc.wrapping_add(values[index].rotate_left((index % 47) as u32));
            acc = mix(acc, values[index].wrapping_mul(index as u64 + 3));
            index += 1;
        }
        acc
    }
}
// <<< support

"""


def stage_body(rng: random.Random, module: int, stage: int) -> str:
    """One realistic ~45-line function body, varied deterministically."""
    constant = rng.randrange(1 << 32, 1 << 63)
    mask = rng.randrange(3, 15)
    shift = rng.randrange(1, 31)
    previous = stage - 1
    call = (
        f"    acc = acc.wrapping_add(stage_{previous:02}(acc, depth.saturating_sub(1)));\n"
        if previous >= 0
        else "    acc = acc.wrapping_add(small(acc));\n"
    )
    arms = "\n".join(
        (f"        {index} => " if index < 7 else "        _ => ")
        + f"acc.wrapping_add(0x{constant ^ (index * 0x9e37_79b9):x})"
        + (".rotate_left(index as u32)" if index % 2 else ".wrapping_mul(index as u64 + 1)")
        + ","
        for index in range(8)
    )
    return f"""    #[inline(never)]
    fn stage_{stage:02}(seed: u64, depth: u32) -> u64 {{
        let mut acc = seed ^ 0x{constant:x};
        let mut buffer: alloc::vec::Vec<u64> = alloc::vec::Vec::with_capacity(24);
        let mut index = 0usize;
        while index < 24 {{
            let raw = (index as u64)
                .wrapping_mul(0x{constant:x})
                .wrapping_add(seed.rotate_left((index % {shift}) as u32));
            if raw & {mask} == 0 {{
                index += 1;
                continue;
            }}
            buffer.push(match raw & 7 {{
                0 => raw.wrapping_add(0x{constant & 0xffff:x}),
                1 => raw.wrapping_mul(3).rotate_left(7),
                2 => raw ^ 0x{constant:x},
                3 => raw.wrapping_sub(index as u64),
                4 => raw.rotate_right((index % 29) as u32),
                5 => raw.wrapping_add(0x9e37_79b9_7f4a_7c15),
                6 => raw.wrapping_mul(0xbf58_476d_1ce4_e5b9),
                _ => raw.wrapping_add(0x94d0_49bb_1331_11eb),
            }});
            index += 1;
        }}
        let folded = buffer
            .iter()
            .copied()
            .enumerate()
            .filter(|(slot, value)| (value ^ *slot as u64) & 1 == 0)
            .map(|(slot, value)| value.rotate_left((slot % {shift}) as u32))
            .fold(acc, |left, right| left.wrapping_add(right));
        acc = acc.wrapping_mul(0x{constant:x}).wrapping_add(folded);
{call}        match acc & 7 {{
{arms}
        }}
    }}

"""


def module_text(rng: random.Random, module: int, stages: int) -> str:
    name = f"m{module:03}"
    key = f"Key{module}"
    value = f"Value{module}"
    record = f"Record{module}"
    kind = f"Kind{module}"
    lines = [f"// >>> {name}\nmod {name} {{\n"]
    lines.append(
        "    use super::support::{Metric, Reducer, Table, Window, checksum, combine, mix};\n"
        "    use super::emit_u64;\n\n"
    )
    lines.append(
        f"    #[derive(Clone, Copy, PartialEq)]\n"
        f"    pub struct {key}(pub u32);\n\n"
        f"    #[derive(Clone, Copy)]\n"
        f"    pub struct {value}(pub u32);\n\n"
        f"    impl From<{value}> for u64 {{\n"
        f"        #[inline]\n"
        f"        fn from(value: {value}) -> u64 {{\n"
        f"            value.0 as u64\n"
        f"        }}\n"
        f"    }}\n\n"
    )
    lines.append(
        f"    #[derive(Clone, Copy)]\n"
        f"    pub struct {record} {{\n"
        f"        pub id: u32,\n"
        f"        pub weight: u64,\n"
        f"        pub flags: u16,\n"
        f"    }}\n\n"
        f"    #[derive(Clone, Copy)]\n"
        f"    pub enum {kind} {{\n"
        f"        Alpha(u64),\n"
        f"        Beta {{ value: u32 }},\n"
        f"        Gamma(u16),\n"
        f"    }}\n\n"
    )
    const_a = rng.randrange(1 << 16, 1 << 40)
    const_b = rng.randrange(1 << 16, 1 << 40)
    lines.append(
        f"    impl Metric for {record} {{\n"
        f"        #[inline]\n"
        f"        fn score(&self) -> u64 {{\n"
        f"            self.weight\n"
        f"                .wrapping_mul(0x{const_a:x})\n"
        f"                .wrapping_add((self.id as u64).rotate_left((self.flags % 31) as u32))\n"
        f"        }}\n\n"
        f"        #[inline]\n"
        f"        fn weight(&self) -> u32 {{\n"
        f"            (self.flags as u32).wrapping_add(self.id)\n"
        f"        }}\n"
        f"    }}\n\n"
        f"    impl Metric for {kind} {{\n"
        f"        #[inline]\n"
        f"        fn score(&self) -> u64 {{\n"
        f"            match *self {{\n"
        f"                {kind}::Alpha(value) => value.wrapping_mul(0x{const_a:x}),\n"
        f"                {kind}::Beta {{ value }} => (value as u64).rotate_left(11),\n"
        f"                {kind}::Gamma(value) => (value as u64).wrapping_add(0x{const_b:x}),\n"
        f"            }}\n"
        f"        }}\n\n"
        f"        #[inline]\n"
        f"        fn weight(&self) -> u32 {{\n"
        f"            match *self {{\n"
        f"                {kind}::Alpha(value) => value as u32,\n"
        f"                {kind}::Beta {{ value }} => value,\n"
        f"                {kind}::Gamma(value) => value as u32,\n"
        f"            }}\n"
        f"        }}\n"
        f"    }}\n\n"
        f"    impl Reducer for {record} {{\n"
        f"        #[inline(never)]\n"
        f"        fn reduce(&self, seed: u64) -> u64 {{\n"
        f"            let parts = [self.id as u64, self.weight, self.flags as u64];\n"
        f"            checksum::<3>(seed, &parts)\n"
        f"        }}\n"
        f"    }}\n\n"
    )
    # A small #[inline] helper becomes a LocalCopy item, so the partitioner's
    # inlined-copy path is exercised.
    lines.append(
        f"    #[inline]\n"
        f"    fn small(value: u64) -> u64 {{\n"
        f"        mix(value, 0x{const_b:x}).wrapping_add(0x{const_a & 0xffff:x})\n"
        f"    }}\n\n"
    )
    for stage in range(stages):
        if module == 16 and stage == 6:
            lines.append("    // @edit:signature\n")
        lines.append(stage_body(rng, module, stage))
    if module == 64:
        lines.append(
            "    // @edit:one-function\n"
            "    #[inline(never)]\n"
            "    pub fn hot_edit(seed: u64) -> u64 {\n"
            "        let mut acc = seed.wrapping_mul(0x9e37_79b9_7f4a_7c15);\n"
            "        acc = acc.rotate_left(13).wrapping_add(0x1234_5678);\n"
            "        acc ^ seed.rotate_right(7)\n"
            "    }\n\n"
        )
    if module == 48:
        lines.append(
            "    // @edit:struct-layout\n"
            f"    pub struct Packet{module} {{\n"
            "        pub tag: u16,\n"
            "        pub payload: u64,\n"
            "    }\n\n"
        )
    if module == 32:
        lines.append(
            "    // @edit:add-function\n"
            f"    #[inline(never)]\n"
            f"    pub fn added_{module:03}(seed: u64) -> u64 {{\n"
            "        let words = [seed, seed.rotate_left(9), seed ^ 0x55aa];\n"
            "        checksum::<3>(seed, &words)\n"
            "    }\n\n"
        )
    # The public entry point: generic table/window instances, a trait object,
    # its module's stage chain, and the support helpers used crate-wide.
    calls = "\n".join(
        f"        acc = acc.wrapping_add(stage_{stage:02}(acc, 1));" for stage in range(stages)
    )
    lines.append(
        "    #[inline(never)]\n"
        f"    pub fn run(seed: u64) -> u64 {{\n"
        f"        let mut table: Table<{key}, u64> = Table::new();\n"
        f"        let mut window: Window<{value}> = Window::new();\n"
        "        let mut index = 0u32;\n"
        "        while index < 24 {\n"
        f"            table.insert({key}(index.wrapping_mul(9).wrapping_add({module})), (index as u64).wrapping_add(seed));\n"
        f"            window.push({value}(index.wrapping_mul(3).wrapping_add({module})));\n"
        "            index += 1;\n"
        "        }\n"
        "        let samples = [\n"
        f"            seed ^ 0x{const_a:x},\n"
        "            seed.rotate_left(13),\n"
        f"            mix(seed, 0x{const_b:x}),\n"
        "        ];\n"
        "        let mut acc = combine(seed, &samples);\n"
    )
    if module == 32:
        lines.append("        acc = acc.wrapping_add(added_032(seed));\n")
    lines.append(calls + "\n")
    if module == 64:
        lines.append("        acc = acc.wrapping_add(hot_edit(seed));\n")
    if module == 48:
        lines.append(
            "        let packet = Packet48 { tag: (seed as u16) ^ 48, payload: acc }; "
            "acc = acc.wrapping_add(packet.payload ^ packet.tag as u64);\n"
        )
    lines.append(
        f"        let record = {record} {{\n"
        f"            id: (seed as u32).wrapping_add({module}),\n"
        "            weight: acc.rotate_left(5),\n"
        f"            flags: (seed as u16) ^ {module},\n"
        "        };\n"
        f"        let kind = {kind}::Beta {{ value: acc as u32 }};\n"
        f"        let metrics: [&dyn Metric; 2] = [&record, &kind];\n"
        "        for metric in metrics {\n"
        "            acc = acc.wrapping_add(metric.score());\n"
        "            acc = acc.rotate_left(metric.weight() % 31);\n"
        "        }\n"
        f"        acc = acc.wrapping_add(table.lookup({key}({module} * 9)).unwrap_or(0));\n"
        "        acc = acc.wrapping_add(table.len() as u64);\n"
        "        acc = acc.wrapping_add(window.weighted_sum(acc));\n"
        "        acc = acc.wrapping_add(record.reduce(acc));\n"
        "        emit_u64(acc);\n"
        "        acc\n"
        "    }\n"
    )
    lines.append(f"}}\n// <<< {name}\n\n")
    return "".join(lines)


def generate(prelude: Path, modules: int, stages: int, seed: int) -> str:
    rng = random.Random(seed)
    text = HEADER.format(seed=seed, modules=modules, functions=0, lines=0, prelude=prelude)
    text += SUPPORT
    for module in range(modules):
        text += module_text(rng, module, stages)
    names = ",\n    ".join(f"m{module:03}::run" for module in range(modules))
    text += (
        f"static MODULES: [fn(u64) -> u64; {modules}] = [\n    {names},\n];\n\n"
        "fn body(seed: u64) -> u64 {\n"
        "    let mut acc = splitmix64(seed);\n"
        "    let mut index = 0usize;\n"
        "    while index < MODULES.len() {\n"
        "        acc = acc.rotate_left(1) ^ MODULES[index](acc);\n"
        "        if index % 16 == 0 {\n"
        "            emit_u64(acc);\n"
        "        }\n"
        "        index += 1;\n"
        "    }\n"
        "    emit_u64(acc);\n"
        "    acc\n"
        "}\n\n"
        "const BENCH_EDIT_TWEAK: u64 = 0u64;\n"
        "#[unsafe(no_mangle)]\n"
        "pub extern \"C\" fn bench_edit_probe() -> u64 {\n"
        "    BENCH_EDIT_TWEAK\n"
        "}\n"
    )
    return text


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prelude", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--modules", type=int, default=144)
    parser.add_argument("--stages", type=int, default=12)
    parser.add_argument("--seed", type=int, default=20261123)
    args = parser.parse_args()
    prelude = args.prelude.resolve()
    text = generate(prelude, args.modules, args.stages, args.seed)
    # The header claims a line count; fill it in now that the body is built.
    line_count = len(text.splitlines())
    text = text.replace(
        f"// {args.modules} modules, 0 functions, about 0 lines.",
        f"// {args.modules} modules, about {line_count} lines.",
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(text.splitlines())} lines, {len(text)} bytes)")


if __name__ == "__main__":
    main()
