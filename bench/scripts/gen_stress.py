#!/usr/bin/env python3
"""Generate the large codegen-stress benchmark.

The output is deterministic and is written outside the repository's tracked
tree (bench/work/generated_stress.rs). It has many generic instantiations and
many small functions, which is the shape a code generator has to handle for a
real multi-module crate.
"""

from __future__ import annotations

import argparse
from pathlib import Path

TRAITS = 8
TYPES = 8
VARIANTS = 128
FUNCTIONS_PER_MODULE = 128
HEADER = """// Generated by bench/scripts/gen_stress.py. Do not edit.
#![no_std]

include!("{prelude}");

"""


def value_expr(type_index: int) -> str:
    return f"self.field.wrapping_mul({type_index + 3}).wrapping_add({type_index * 17 + 1})"


def generate(prelude: Path) -> str:
    lines = [HEADER.format(prelude=prelude)]
    for trait in range(TRAITS):
        lines.append(f"trait T{trait} {{ fn v{trait}(&self) -> u64; }}\n")
    for type_index in range(TYPES):
        lines.append(f"struct S{type_index} {{ field: u64 }}\n")
        lines.append(f"impl S{type_index} {{ const fn new(field: u64) -> Self {{ Self {{ field }} }} }}\n")
        for trait in range(TRAITS):
            lines.append(
                f"impl T{trait} for S{type_index} {{ "
                f"#[inline] fn v{trait}(&self) -> u64 {{ {value_expr(type_index)} }} }}\n"
            )
    bounds = " + ".join(f"T{trait}" for trait in range(TRAITS))
    lines.append(
        f"#[inline(never)]\nfn combine<T: {bounds}>(value: &T, seed: u64) -> u64 {{\n"
        "    let mut acc = seed;\n"
    )
    for trait in range(TRAITS):
        lines.append(
            f"    acc = acc.wrapping_mul(0x9e37_79b9_7f4a_7c15).wrapping_add(value.v{trait}());\n"
        )
    lines.append("    acc\n}\n\n")
    # Split the 1,024 functions into inline modules so rustc partitions the
    # crate into one codegen unit per module. A single flat module gives one
    # codegen unit for the whole crate, which cannot be split by
    # -Ccodegen-units and makes the program useless for testing per-part
    # rebuilds. Groups of 64 variants give 16 modules.
    groups = (TYPES * VARIANTS) // FUNCTIONS_PER_MODULE
    for group in range(groups):
        lines.append(f"mod part{group} {{\n")
        for offset in range(FUNCTIONS_PER_MODULE):
            index = group * FUNCTIONS_PER_MODULE + offset
            type_index = index // VARIANTS
            variant = index % VARIANTS
            lines.append(
                f"    #[inline(never)]\n    pub fn w_{type_index}_{variant}(seed: u64) -> u64 {{\n"
                f"        let value = super::S{type_index}::new(seed ^ {variant * 2654435761 + 1});\n"
                "        super::combine(&value, seed)\n    }\n\n"
            )
        lines.append("}\n\n")
    count = TYPES * VARIANTS
    names = ", ".join(
        f"part{(t * VARIANTS + v) // FUNCTIONS_PER_MODULE}::w_{t}_{v}"
        for t in range(TYPES)
        for v in range(VARIANTS)
    )
    lines.append(f"static FUNCTIONS: [fn(u64) -> u64; {count}] = [{names}];\n\n")
    lines.append("fn body(seed: u64) -> u64 {\n    let mut acc = 0u64;\n")
    lines.append("    let mut index = 0usize;\n    while index < FUNCTIONS.len() {\n")
    lines.append("        acc = acc.wrapping_add(FUNCTIONS[index](seed));\n")
    lines.append("        if index % 64 == 0 {\n            emit_u64(acc);\n        }\n")
    lines.append("        index += 1;\n    }\n")
    lines.append("    emit_u64(acc);\n    acc\n}\n")
    return "".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prelude", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    prelude = args.prelude.resolve()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generate(prelude), encoding="utf-8")
    print(f"wrote {args.out} ({len(generate(prelude).splitlines())} lines)")


if __name__ == "__main__":
    main()
